func TestStale(t *testing.T) {
	t.Parallel()
	is := is.New(t)
	dir := write(t, virt.Map{
		"views/props.go": `
			package views

			type Props struct {
				Name string ´json:"name"´
			}
		`,
		"views/routes.go": `
			package views

			type routes struct{}
		`,
		"views/routes.go.ts":    "// Code generated by jig. DO NOT EDIT.\n",
		"views/removed.go.ts":   "// Code generated by jig. DO NOT EDIT.\n",
		"views/handmade.go.ts":  "export type Handmade = string\n",
		"views/empty/empty.ts":  "export {}\n",
		"views/empty/old.go.ts": "// Code generated by jig. DO NOT EDIT.\n",
	})
	views := filepath.Join(dir, "views")
	ctx := context.Background()
	log := slog.New(slog.DiscardHandler)
	is.NoErr(typegen.Generate(ctx, log, views))
	outputs := generated(t, dir)
	is.Equal(len(outputs), 2)
	is.Equal(outputs["views/handmade.go.ts"], "export type Handmade = string\n")
	is.True(outputs["views/props.go.ts"] != "")

	// Unchanged files aren't written again
	past := time.Now().Add(-time.Hour).Truncate(time.Second)
	propsPath := filepath.Join(views, "props.go.ts")
	is.NoErr(os.Chtimes(propsPath, past, past))
	is.NoErr(typegen.Generate(ctx, log, views))
	info, err := os.Stat(propsPath)
	is.NoErr(err)
	is.True(info.ModTime().Equal(past))

	// Removing the Go file removes its types
	is.NoErr(os.Remove(filepath.Join(views, "props.go")))
	is.NoErr(typegen.Generate(ctx, log, views))
	outputs = generated(t, dir)
	is.Equal(len(outputs), 1)
}

